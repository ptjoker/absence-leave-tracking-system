function pdfEscape(value) {
  return String(value ?? '').replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
}

function makePdf(rows, title) {
  const wrap = (value, max) => {
    const words = String(value ?? '').split(/\s+/);
    const lines = [];
    let line = '';
    words.forEach((word) => {
      if (line && `${line} ${word}`.length > max) { lines.push(line); line = word; }
      else line = line ? `${line} ${word}` : word;
    });
    if (line) lines.push(line);
    return lines.length ? lines : [''];
  };
  const pages = [];
  let page = [
    { type: 'text', value: title, size: 16 },
    { type: 'text', value: 'StudentAssist Performance Report', size: 10 },
    { type: 'text', value: `Generated: ${new Date().toLocaleDateString('en-ZA')}`, size: 10 },
    { type: 'text', value: `Report period: ${title.replace(/^Performance Reports\s*[—-]?\s*/, '')}`, size: 10 },
  ];
  let estimatedHeight = 110;
  const addPage = () => {
    if (page.length) pages.push(page);
    page = [];
    estimatedHeight = 0;
  };
  const addTable = (label, headers, tableRows) => {
    if (!tableRows.length) return;
    const chunkSize = headers.length === 6 ? 18 : 14;
    for (let index = 0; index < tableRows.length; index += chunkSize) {
      const chunk = tableRows.slice(index, index + chunkSize);
      const heading = index === 0 ? label : `${label} (continued)`;
      if (estimatedHeight + (chunk.length + 2) * 22 > 690) addPage();
      page.push({ type: 'text', value: heading, size: 10 });
      page.push({ type: 'table', headers, rows: chunk });
      estimatedHeight += (chunk.length + 2) * 22;
      if (index + chunkSize < tableRows.length) addPage();
    }
  };
  addTable('Performance Summary', ['Student Assistant', 'Hours', 'Requests', 'Days', 'Site', 'Shifts'], rows.map((row) => [row.name, row.hours, row.requests, row.requestDays || 0, row.site, row.days]));
  rows.forEach((row) => {
    addTable(`Shift details — ${row.name}`, ['Date', 'Position', 'Time', 'Duration'], row.shiftDetails ? row.shiftDetails.split(' ; ').map((detail) => detail.split(' | ')) : []);
    addTable(`Request details — ${row.name}`, ['Type', 'Date range', 'Days', 'Status'], row.requestDetails ? row.requestDetails.split(' ; ').map((detail) => detail.split(' | ')) : []);
  });
  addPage();

  const objects = [];
  objects.push('<< /Type /Catalog /Pages 2 0 R >>');
  const pageObjectNumbers = [];
  let nextObject = 5;
  pages.forEach(() => { pageObjectNumbers.push(nextObject); nextObject += 2; });
  objects.push(`<< /Type /Pages /Kids [${pageObjectNumbers.map((n) => `${n} 0 R`).join(' ')}] /Count ${pages.length} >>`);
  objects.push('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
  objects.push('<< /Producer (StudentAssist) >>');

  pages.forEach((pageLines, pageIndex) => {
    const pageNumber = pageObjectNumbers[pageIndex];
    const contentNumber = pageNumber + 1;
    const commands = [];
    let y = 565;
    const drawText = (value, size = 10) => {
      commands.push(`BT /F1 ${size} Tf 40 ${y} Td (${pdfEscape(value)}) Tj ET`);
      y -= size === 16 ? 26 : 18;
    };
    const drawTable = (table) => {
      const widths = table.headers.length === 6 ? [135, 62, 62, 62, 105, 62] : [115, 145, 145, 115];
      const rowsToDraw = [table.headers, ...table.rows];
      rowsToDraw.forEach((row, rowIndex) => {
        const wrapped = row.map((value, index) => wrap(value, Math.max(8, Math.floor(widths[index] / 5))));
        const height = Math.max(...wrapped.map((lines) => lines.length)) * 11 + 8;
        let x = 40;
        row.forEach((value, index) => {
          const width = widths[index] || 100;
          const bottom = y - height;
          commands.push(`${rowIndex === 0 ? '0.05 0.25 0.42 rg' : '0.96 0.98 1 rg'} ${x} ${bottom} ${width} ${height} re f`, `0 0 0 RG ${x} ${bottom} ${width} ${height} re S`);
          wrapped[index].forEach((line, lineIndex) => {
            commands.push(`BT /F1 ${rowIndex === 0 ? 8 : 7} Tf ${rowIndex === 0 ? '1 1 1 rg' : '0 0 0 rg'} ${x + 4} ${y - 14 - (lineIndex * 11)} Td (${pdfEscape(line)}) Tj ET`);
          });
          x += width;
        });
        y -= height;
      });
      y -= 12;
    };
    pageLines.forEach((item) => {
      if (item.type === 'text') drawText(item.value, item.size);
      else drawTable(item);
    });
    const stream = commands.join('\n');
    objects.push(`<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R >> >> /Contents ${contentNumber} 0 R >>`);
    objects.push(`<< /Length ${new TextEncoder().encode(stream).length} >>\nstream\n${stream}\nendstream`);
  });

  const chunks = ['%PDF-1.4\n%\u00e2\u00e3\u00cf\u00d3\n'];
  const offsets = [0];
  const encoder = new TextEncoder();
  let position = encoder.encode(chunks[0]).length;
  objects.forEach((obj, index) => {
    offsets[index + 1] = position;
    const chunk = `${index + 1} 0 obj\n${obj}\nendobj\n`;
    chunks.push(chunk);
    position += encoder.encode(chunk).length;
  });
  const xrefOffset = position;
  let xref = `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (let i = 1; i <= objects.length; i += 1) xref += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
  const trailer = `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;
  chunks.push(xref, trailer);
  return new TextEncoder().encode(chunks.join(''));
}

export function exportPerformanceReport(format, rows, title = 'Performance Reports') {
  const safeDate = new Date().toISOString().slice(0, 10);
  if (format === 'csv') {
    const header = 'Report Period,Student Assistant,Hours Worked,Total Requests,Site,Days,Shift Details';
    const periodLine = title.replace(/^Performance Reports\s*[—-]?\s*/, '');
    const body = rows.map((row) => [periodLine, row.name, row.hours, row.requests, row.site, row.days, row.shiftDetails || ''].map((value) => `"${String(value ?? '').replace(/"/g, '""')}"`).join(','));
    downloadBlob([header, ...body].join('\n'), `studentassist-performance-${safeDate}.csv`, 'text/csv;charset=utf-8');
    return;
  }
  if (format === 'excel') {
    const bytes = makeExcelXml(rows, title);
    downloadBlob(new Blob([bytes], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' }), `studentassist-performance-${safeDate}.xlsx`);
    return;
  }
  if (format === 'docx') {
    const bytes = makeDocx(rows, title);
    downloadBlob(new Blob([bytes], { type: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document' }), `studentassist-performance-${safeDate}.docx`);
    return;
  }
  if (format === 'pdf') {
    const bytes = makePdf(rows, title);
    downloadBlob(new Blob([bytes], { type: 'application/pdf' }), `studentassist-performance-${safeDate}.pdf`);
  }
}

function requestDetails(request) {
  const details = request.details || {};
  if (request.requestType === 'Shift Swap') {
    const original = details.originalShift || {};
    const proposed = details.proposedShift || {};
    return [
      `Original shift: ${original.date || '—'} ${original.start || ''}-${original.end || ''}`,
      `Proposed shift: ${proposed.date || '—'} ${proposed.start || ''}-${proposed.end || ''}`,
      `Replacement: ${details.replacementStudentAssistant || '—'}`,
      details.replacementResponse ? `Replacement response: ${details.replacementResponse}` : '',
    ].filter(Boolean).join(' | ');
  }
  return [
    details.leaveType ? `Leave type: ${details.leaveType}` : '',
    details.dates ? `Dates: ${details.dates}` : '',
    details.replacement ? `Replacement: ${details.replacement}` : '',
  ].filter(Boolean).join(' | ');
}

function makeRequestPdf(requests, filters) {
  const clean = (value) => String(value ?? '').normalize('NFKD').replace(/[^\x20-\x7E]/g, '?');
  const wrap = (value, width = 92) => {
    const words = clean(value).split(/\s+/);
    const lines = [];
    let line = '';
    words.forEach((word) => {
      if (line && `${line} ${word}`.length > width) {
        lines.push(line);
        line = word;
      } else {
        line = line ? `${line} ${word}` : word;
      }
    });
    if (line) lines.push(line);
    return lines;
  };
  const filterSummary = [
    filters.type && `Type: ${filters.type}`,
    filters.status && `Status: ${filters.status}`,
    filters.from && `From: ${filters.from}`,
    filters.to && `To: ${filters.to}`,
    filters.q && `Search: ${filters.q}`,
  ].filter(Boolean).join(' | ') || 'All request records';
  const lines = [
    'iCenter Admin Request Report',
    `Generated: ${new Date().toLocaleString('en-GB')}`,
    `Filters: ${filterSummary}`,
    `Requests: ${requests.length}`,
    '',
    ...requests.flatMap((request) => [
      ...wrap(`${request.id} | ${request.requestType} | ${request.status} | Submitted ${request.requestDate || '—'}`),
      ...wrap(`Assistant: ${request.studentAssistant?.name || 'Unknown'} | ${request.studentAssistant?.studentNumber || 'No student number'} | ${request.studentAssistant?.email || 'No email'}`),
      ...wrap(`Requested date: ${request.requestedDate || '—'} | Reason: ${request.reason || '—'}`),
      ...wrap(`Details: ${requestDetails(request) || '—'}`),
      ...wrap(`Supervisor decision: ${request.supervisorDecision?.decision || 'Pending'}${request.supervisorDecision?.comments ? ` - ${request.supervisorDecision.comments}` : ''}`),
      '',
    ]),
  ];
  const pages = [];
  for (let index = 0; index < lines.length; index += 38) pages.push(lines.slice(index, index + 38));

  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
  ];
  const pageNumbers = pages.map((_, index) => 5 + index * 2);
  objects.push(`<< /Type /Pages /Kids [${pageNumbers.map((number) => `${number} 0 R`).join(' ')}] /Count ${pages.length} >>`);
  objects.push('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
  objects.push('<< /Producer (iCenter) >>');
  pages.forEach((pageLines, pageIndex) => {
    const pageNumber = pageNumbers[pageIndex];
    const commands = ['BT', '/F1 9 Tf', '40 760 Td'];
    pageLines.forEach((line, lineIndex) => {
      if (pageIndex === 0 && lineIndex === 0) commands.push('/F1 16 Tf');
      else if (pageIndex === 0 && lineIndex === 1) commands.push('/F1 9 Tf');
      commands.push(`(${pdfEscape(line)}) Tj`, '0 -18 Td');
    });
    commands.push('ET');
    const stream = commands.join('\n');
    objects.push(`<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R >> >> /Contents ${pageNumber + 1} 0 R >>`);
    objects.push(`<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`);
  });

  const chunks = ['%PDF-1.4\n%PDF\n'];
  const offsets = [0];
  let position = chunks[0].length;
  objects.forEach((object, index) => {
    offsets[index + 1] = position;
    const chunk = `${index + 1} 0 obj\n${object}\nendobj\n`;
    chunks.push(chunk);
    position += chunk.length;
  });
  const xrefOffset = position;
  const xref = `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n${offsets.slice(1).map((offset) => `${String(offset).padStart(10, '0')} 00000 n \n`).join('')}`;
  chunks.push(xref, `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`);
  return new TextEncoder().encode(chunks.join(''));
}

